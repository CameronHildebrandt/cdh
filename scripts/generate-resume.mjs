import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import { createInterface } from 'node:readline/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dataPath = resolve(root, 'src/data/resume-data.json');
const previewDirectory = resolve(root, 'resume-tmp');
const publish = process.argv.includes('--publish');
const outputPath = resolve(previewDirectory, 'resume.tex');
const publishPath = resolve(root, 'src/data/resume.tex');
const selectAll = process.argv.includes('--all') || !process.stdin.isTTY;
const readline = selectAll ? null : createInterface({ input: process.stdin, output: process.stdout });

const data = JSON.parse(await readFile(dataPath, 'utf8'));
const allIndexes = (items) => items.map((_, index) => index);
const texEscapes = {
  '\\': '\\textbackslash{}', '&': '\\&', '%': '\\%', '$': '\\$', '#': '\\#',
  '_': '\\_', '{': '\\{', '}': '\\}', '→': '$\\rightarrow$',
};
const monthIndexes = Object.fromEntries([
  'jan', 'feb', 'mar', 'apr', 'may', 'jun',
  'jul', 'aug', 'sep', 'oct', 'nov', 'dec',
].map((month, index) => [month, index]));

const toTex = (value) => [...value].map((character) => texEscapes[character] ?? character).join('');

function parseSelection(value, itemCount) {
  const answer = value.trim().toLowerCase();
  if (!answer || answer === 'all') return allIndexes(Array(itemCount));
  if (answer === 'none') return [];

  const selected = [...new Set(answer.split(',').map((part) => Number(part.trim()) - 1))]
    .filter((index) => Number.isInteger(index) && index >= 0 && index < itemCount);
  if (!selected.length) throw new Error('Choose comma-separated item numbers, “all”, “none”, or press Enter for all.');
  return selected;
}

async function choose(label, items, format) {
  if (selectAll) return allIndexes(items);
  console.log(`\n${label}`);
  items.forEach((item, index) => console.log(`  ${index + 1}. ${format(item)}`));

  while (true) {
    try {
      return parseSelection(await readline.question('Select numbers (Enter = all): '), items.length);
    } catch (error) {
      console.log(error.message);
    }
  }
}

function formatDuration(dates) {
  const match = dates.match(/^([A-Za-z]{3})\.?\s+(\d{4})\s*-\s*(Present|([A-Za-z]{3})\.?\s+(\d{4}))$/);
  if (!match) return '';

  const startMonth = monthIndexes[match[1].toLowerCase()];
  const startYear = Number(match[2]);
  const end = match[3] === 'Present'
    ? new Date()
    : new Date(Number(match[5]), monthIndexes[match[4].toLowerCase()], 1);
  if (startMonth === undefined || Number.isNaN(startYear) || Number.isNaN(end.getTime())) return '';

  const totalMonths = Math.max(0, (end.getFullYear() - startYear) * 12 + end.getMonth() - startMonth);
  const years = Math.floor(totalMonths / 12);
  const months = totalMonths % 12;
  return `${years ? `${years}y` : ''}${years && months ? ' ' : ''}${months ? `${months}m` : ''}`;
}

function renderExperience(experience) {
  const duration = formatDuration(experience.dates);

  return String.raw`\resumeHeading
{${toTex(experience.role)}}
{${toTex(experience.company)} - ${toTex(experience.city)}}
{${toTex(experience.dates)}}
{${duration}}

\begin{itemize}
${experience.highlights.map((highlight) => `\\item ${toTex(highlight)}`).join('\n')}
\end{itemize}
\resumeFooting{}`;
}

