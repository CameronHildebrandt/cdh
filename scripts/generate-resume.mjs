function revealInFinder(path) {
  return new Promise((resolveReveal) => {
    const finder = spawn('open', ['-R', path], { stdio: 'ignore' });
    finder.once('error', () => {
      console.warn('Could not reveal the generated file in Finder.');
      resolveReveal();
    });
    finder.once('exit', () => resolveReveal());
  });
}

const experienceIndexes = await choose('Experiences', data.experiences, (entry) => `${entry.company} — ${entry.role}`);
const selectedExperiences = experienceIndexes.map((index) => data.experiences[index]);
const selectedSkills = [];

for (const group of data.skills) {
  const indexes = await choose(`Skills / ${group.category}`, group.items, (skill) => skill);
  if (indexes.length) selectedSkills.push({ category: group.category, items: indexes.map((index) => group.items[index]) });
}

try {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, renderResume(selectedExperiences, selectedSkills));
  console.log(`\nGenerated ${outputPath.replace(`${root}/`, '')} with ${selectedExperiences.length} experience(s) and ${selectedSkills.reduce((total, group) => total + group.items.length, 0)} skill(s).`);
  if (publish) {
    await copyFile(outputPath, publishPath);
    console.log(`Published ${publishPath.replace(`${root}/`, '')}.`);
  }
  await revealInFinder(outputPath);
} finally {
  readline?.close();
}
